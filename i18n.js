let currentLang = localStorage.getItem('wg_selected_lang') || 'fr';

function setLanguage(lang) {
    if (!WG_I18N[lang]) lang = 'fr';
    currentLang = lang;
    localStorage.setItem('wg_selected_lang', lang);
    applyTranslations();

    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    // Notify other components
    window.dispatchEvent(new CustomEvent('wg:languageChanged', { detail: { lang } }));
}

function t(key) {
    const dict = WG_I18N[currentLang] || WG_I18N['fr'];
    return dict[key] || WG_I18N['fr'][key] || key;
}

function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translated = t(key);
        if (translated) {
            el.innerHTML = translated;
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        const translated = t(key);
        if (translated) {
            el.setAttribute('placeholder', translated);
        }
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        const translated = t(key);
        if (translated) {
            el.setAttribute('title', translated);
        }
    });
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            const l = btn.getAttribute('data-lang');
            setLanguage(l);
        });
    });
});
